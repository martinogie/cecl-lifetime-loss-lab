"""Apply ADR-009's selection rule to the validation runs and write the validation report (step 6).

    CECL_ENV=dev python -m scripts.select_model

Reads, from the dev MLflow experiment, the newest validation run of each family (not the COVID
sensitivity run), applies `cecl.models.selection.choose`, logs a `selection` run with the decision,
and writes docs/phase2/validation_report.md (aggregate measures only). API calls, no compute.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from cecl import tracking
from cecl.models import selection
from cecl.models.families import SIMPLICITY_ORDER

REPORT = Path("docs/phase2/validation_report.md")


def latest_validation_runs(mlflow: Any) -> dict[str, Any]:
    runs = mlflow.search_runs(filter_string="tags.stage = 'validation' and tags.sensitivity = 'none'",
                              order_by=["start_time DESC"], output_format="list")  # fmt: skip
    newest: dict[str, Any] = {}
    for r in runs:
        newest.setdefault(r.data.tags["family"], r)
    return newest


def report_markdown(
    choice: selection.Choice, details: dict[str, dict[str, Any]], run_ids: dict[str, str]
) -> str:
    lines = ["# Phase 2: validation report (2017-2019, every measure weighted)", "",
             "Generated by `scripts/select_model.py` from the MLflow validation runs; the rule is ADR-009 (C1).", "",
             "| Family | Run | Log loss (default) | vs benchmark | AUC (Gini) default | AUC (Gini) prepay | AUC (Gini) 12/24/36 months | "
             "Calibration bars | Reason codes | Qualifies |", "|---|---|---|---|---|---|---|---|---|---|"]  # fmt: skip
    for row in choice.table:
        d = details[row["family"]]
        hz = d.get("auc_by_horizon") or {}
        horizon = " / ".join(
            f"{hz[h]['auc']:.3f} ({2 * hz[h]['auc'] - 1:.3f})" if h in hz else "-" for h in ("12", "24", "36")
        )  # Gini = 2 x AUC - 1
        lines.append(
            f"| {row['family']} | `{run_ids[row['family']][:8]}` | {row['log_loss_default']:.5f} | "
            f"{row['improvement']:+.1%} | {d['auc_default']:.3f} ({2 * d['auc_default'] - 1:.3f}) | {d['auc_prepay']:.3f} ({2 * d['auc_prepay'] - 1:.3f}) | {horizon} | "
            f"{'pass' if row['calibration_passes'] else 'FAIL'} | {'yes' if row['reason_codes'] else 'no'} | "
            f"{'benchmark' if row['family'] == selection.BENCHMARK else ('yes' if row.get('qualifies') else 'no')} |"
        )
    lines += ["", f"**Chosen: {choice.chosen}.**", ""] + [f"- {r}" for r in choice.reasons]
    lines += ["", "Calibration tables (predicted / actual, by year and vintage, both causes) are in each run's "
              "`validation.json` artefact. The out-of-time test has not been run yet.", ""]  # fmt: skip
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--root", type=Path, default=Path("data"))
    parser.parse_args(argv)
    import mlflow

    tracking.configure(mlflow)
    runs = latest_validation_runs(mlflow)
    missing = [f for f in SIMPLICITY_ORDER if f not in runs]
    if missing:
        raise SystemExit(f"no validation run yet for: {missing}")
    details, results, run_ids = {}, [], {}
    for family, run in runs.items():
        d = mlflow.artifacts.load_dict(f"runs:/{run.info.run_id}/validation.json")
        details[family], run_ids[family] = d, run.info.run_id
        results.append(
            selection.FamilyResult(family, d["log_loss_default"], d["calibration_passes"], d["reason_codes"])
        )
    choice = selection.choose(results)
    REPORT.write_text(report_markdown(choice, details, run_ids), encoding="utf-8")
    with mlflow.start_run(run_name="selection"):
        mlflow.set_tags(tracking.standard_tags(Path("data")) | {"stage": "selection", "chosen": choice.chosen,
                                                                 "phase": "2"})  # fmt: skip
        mlflow.log_params({f"run_{f}": r for f, r in run_ids.items()})
        mlflow.log_dict(
            {"chosen": choice.chosen, "reasons": choice.reasons, "table": choice.table}, "selection.json"
        )
    print(json.dumps({"chosen": choice.chosen, "reasons": choice.reasons}, indent=1))
    print(f"report: {REPORT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
